/** Compare authored frontend code and runtime changes across incoming PRs and their ports.
 * Generated sources, lockfiles and assets are excluded; public declarations are
 * counted separately from implementation.
 * Pass any two Git revisions; output includes explicit exclusions for auditability.
 */
import { execFileSync } from "node:child_process";
const [before, after] = process.argv.slice(2);
if (!before || !after)
  throw new Error("Usage: node --import tsx scripts/sync-deltas.ts BEFORE AFTER");
const root = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
const git = (...args: string[]) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
const runtime = { added: 0, removed: 0 };
const authored = { added: 0, removed: 0 };
const excluded: string[] = [];
const wholeCode = { added: 0, removed: 0 };
const wholeCodeFiles: { path: string; added: number; removed: number; publicInterface: boolean }[] =
  [];
const files: { path: string; added: number; removed: number; publicInterface: boolean }[] = [];
const rows = git("diff", "--no-renames", "--numstat", before, after);
for (const row of rows.trim().split("\n").filter(Boolean)) {
  const [adds, deletes, path] = row.split("\t") as [string, string, string];
  if (!/\.(ts|js|ml|mli|re|rei|rs|py|svelte|css|html)$/.test(path) || adds === "-") {
    if (/^hex-command\/(src|frontend|public)\//.test(path)) excluded.push(path);
    continue;
  }
  let header = "";
  for (const revision of [after, before]) {
    try {
      header = git("show", `${revision}:${path}`).split("\n").slice(0, 4).join("\n");
      break;
    } catch {
      /* Deleted files are classified from the earlier revision. */
    }
  }
  if (/Generated by|DO NOT EDIT/i.test(header)) {
    if (/^hex-command\/(src|frontend|public)\//.test(path)) excluded.push(path);
    continue;
  }
  const file = {
    path,
    added: Number(adds),
    removed: Number(deletes),
    publicInterface: /\.(mli|rei)$/.test(path) || path.endsWith(".d.ts"),
  };
  wholeCodeFiles.push(file);
  wholeCode.added += file.added;
  wholeCode.removed += file.removed;
  if (!/^hex-command\/(src|frontend|public)\//.test(path)) continue;
  files.push(file);
  authored.added += Number(adds);
  authored.removed += Number(deletes);
  if (!/\.(mli|rei)$/.test(path) && !path.endsWith(".d.ts")) {
    runtime.added += Number(adds);
    runtime.removed += Number(deletes);
  }
}
console.log(
  JSON.stringify(
    {
      before,
      after,
      wholeAuthoredCode: { ...wholeCode, net: wholeCode.added - wholeCode.removed },
      wholeCodeFiles,
      handwrittenFrontend: { ...authored, net: authored.added - authored.removed },
      frontendRuntime: { ...runtime, net: runtime.added - runtime.removed },
      files,
      excluded,
    },
    null,
    2,
  ),
);
