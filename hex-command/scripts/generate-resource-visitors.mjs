// Preserve upstream's content traversal on typed Rust-owned OCaml metadata.
// This emits static field visits: no Obj.magic, JSON conversion or runtime reflection.
import { readFileSync, writeFileSync } from "node:fs";
const schema = JSON.parse(readFileSync("rust/pkg/schema.json", "utf8"));
const snake = (s) =>
  s
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase();
const keywords = new Set(
  "from default effect mod land lor lxor lsl lsr asr and as assert begin class constraint do done downto else end exception external false for fun function functor if in include inherit initializer lazy let match method module mutable new nonrec object of open or private rec sig struct then to true try type val virtual when while with".split(
    " ",
  ),
);
const label = (s) => (keywords.has(snake(s)) ? snake(s) + "_" : snake(s));
const capital = (s) => s[0].toUpperCase() + s.slice(1);
const attr = (s, k) => s?.match(new RegExp(`(?:^|[ (,])${k}\\s*=\\s*"([^"]+)"`))?.[1];
const name = (field, parent = "") =>
  attr(field.serde, "rename") ??
  (attr(parent, "rename_all") === "camelCase"
    ? field.name.replace(/_([a-z])/g, (_, c) => c.toUpperCase())
    : field.name);
const roots = ["MapDefinition", "Mission", "Veteran", "Speech"];
const needed = new Map();
function discover(t) {
  if (t.kind === "array" || t.kind === "slice") return discover(t.inner);
  if (t.kind === "tuple") return t.args.forEach(discover);
  if (t.kind !== "named") throw Error(JSON.stringify(t));
  if (schema[t.name] && !needed.has(t.name)) {
    const e = schema[t.name];
    needed.set(t.name, e);
    if (e.kind === "alias") discover(e.ty);
    else
      for (const b of e.kind === "enum" ? e.variants.map((v) => v.body) : [e.body])
        for (const f of b.fields) discover(f.ty);
  }
  for (const arg of t.args ?? []) discover(arg);
}
roots.forEach((name) => discover({ kind: "named", name, args: [] }));
const mapName = (t) =>
  t.kind === "tuple"
    ? "tuple_" + t.args.map(mapName).join("_")
    : snake(t.name) + (t.args ?? []).map((t) => "_" + mapName(t)).join("");
function walk(t, value) {
  if (t.kind === "array" || t.kind === "slice")
    return `Array.iter (fun value -> ${walk(t.inner, "value")}) (${value})`;
  if (t.kind === "tuple") {
    if (!t.args.length) return "()";
    const vars = t.args.map((_, i) => "v" + i);
    return `(let (${vars.join(",")}) = ${value} in ${t.args.map((t, i) => walk(t, vars[i])).join(";")})`;
  }
  if (t.kind !== "named") throw Error(JSON.stringify(t));
  if (["String", "str"].includes(t.name)) return `visitor.string (${value})`;
  if (t.name === "Option")
    return `Option.iter (fun value -> ${walk(t.args[0], "value")}) (${value})`;
  if (["Vec", "VecDeque"].includes(t.name))
    return `Array.iter (fun value -> ${walk(t.args[0], "value")}) (${value})`;
  if (["Box", "Rc", "Arc"].includes(t.name)) return walk(t.args[0], value);
  if (["HashMap", "BTreeMap"].includes(t.name)) {
    if (t.map === "dict")
      return `Array.iter (fun (_,value) -> ${walk(t.args[1], "value")}) (Js.Dict.entries (${value}))`;
    const module = t.name === "HashMap" ? "Hashtbl" : capital(mapName(t.args[0])) + "_map";
    return `${module}.iter (fun _ value -> ${walk(t.args[1], "value")}) (${value})`;
  }
  if (schema[t.name]) return `walk_${snake(t.name)} visitor (${value})`;
  if (t.name === "bool" || /^[ui](8|16|32|64|128|size)$|^f(32|64)$/.test(t.name)) return "()";
  throw Error("Unsupported content field " + JSON.stringify(t));
}
function field(f, value, parent = "") {
  if (/\bskip\b/.test(f.serde)) return "()";
  return `visitor.field ${JSON.stringify(name(f, parent))} (fun visitor -> ${walk(f.ty, value)})`;
}
let out =
  '(* Generated by scripts/generate-resource-visitors.mjs from the live binding schema.\n   Static typed traversal replaces upstream Object.entries; metadata stays OCaml. *)\n[@@@warning "-27-30-39"]\nopen Domain\ntype visitor = { string : string -> unit; field : string -> (visitor -> unit) -> unit; terrain_change : Domain.terrain_change -> unit }\n';
let first = true;
for (const e of needed.values()) {
  const module = "Domain." + capital(snake(e.name));
  const type = e.kind === "enum" ? module + ".t" : "Domain." + label(e.name);
  out += `${first ? "let rec" : "and"} walk_${snake(e.name)} visitor (value : ${type}) =\n`;
  first = false;
  if (e.name === "TerrainChange") out += "visitor.terrain_change value;\n";
  if (e.kind === "alias") {
    out += walk(e.ty, "value") + "\n";
    continue;
  }
  if (e.kind === "struct") {
    if (e.transparent) out += walk(e.body.fields[0].ty, "value");
    else if (e.body.style === "unit") out += "()";
    else if (e.body.style === "tuple")
      out += walk({ kind: "tuple", args: e.body.fields.map((f) => f.ty) }, "value");
    else
      out +=
        e.body.fields.map((f) => field(f, "value." + label(f.name), e.serde)).join(";\n") || "()";
    out += "\n";
    continue;
  }
  out += "match value with\n";
  for (const variant of e.variants) {
    const b = variant.body,
      fields = b.fields.map((f, i) => (b.style === "named" ? label(f.name) : "v" + i));
    const constructor = module + "." + capital(snake(variant.name));
    const pattern =
      b.style === "unit"
        ? constructor
        : b.style === "named"
          ? `${constructor} {${fields.join(";")}}`
          : `${constructor} (${fields.join(",")})`;
    let operations = [];
    if (b.style === "unit" || attr(e.serde, "tag"))
      operations.push(`visitor.string ${JSON.stringify(variant.serde_name ?? variant.name)}`);
    if (b.style === "named") operations.push(...b.fields.map((f, i) => field(f, fields[i])));
    else if (b.fields.length) operations.push(...b.fields.map((f, i) => walk(f.ty, fields[i])));
    const operation = operations.join(";") || "()";
    if (b.style !== "unit" && !attr(e.serde, "tag") && !e.serde.includes("untagged"))
      out += `| ${pattern} -> visitor.field ${JSON.stringify(variant.serde_name ?? variant.name)} (fun visitor -> ${operation})\n`;
    else out += `| ${pattern} -> ${operation}\n`;
  }
}
writeFileSync("frontend/engine/Domain_resource_walk.ml", out);
