/** Generate only the browser import index; authored values remain in Rust's JSON files. */
import { readFileSync, writeFileSync } from "node:fs";
import { posix } from "node:path";
import { format, resolveConfig } from "prettier";

const root = new URL("../rust/data/", import.meta.url);
const output = new URL("../src/game/content-documents.ts", import.meta.url);
const paths = new Set<string>();
function read<T>(path: string): T {
  if (!path.startsWith("game/") || path.split("/").includes(".."))
    throw new Error(`Invalid content path: ${path}`);
  paths.add(path);
  return JSON.parse(readFileSync(new URL(path, root), "utf8")) as T;
}
function components(path: string, fields: string[]): void {
  const descriptor = read<Record<string, string>>(path);
  for (const field of fields) {
    const component = descriptor[field];
    if (!component) throw new Error(`${path}: missing ${field}`);
    read(posix.join(posix.dirname(path), component));
  }
}
const manifest = JSON.parse(readFileSync(new URL("manifest.json", root), "utf8")) as {
  units: string[];
  terrain: string;
  races: string;
  scenarios: string[];
  campaigns: string[];
};
for (const path of [...manifest.units, manifest.terrain, manifest.races]) read(path);
for (const path of manifest.scenarios) components(path, ["map", "roster"]);
for (const path of manifest.campaigns) {
  const campaign = read<{ stages: string[] }>(path);
  for (const stage of campaign.stages)
    components(posix.join(posix.dirname(path), stage), [
      "map",
      "roster",
      "objectives",
      "story",
      "scripts",
    ]);
}
const documents = [...paths].sort();
const source = await format(
  [
    "// Generated by npm run content:build. Values are imported directly from authored JSON.",
    ...documents.map(
      (path, i) => `import document${i} from ${JSON.stringify("../../rust/data/" + path)};`,
    ),
    "export const CONTENT_DOCUMENTS: Readonly<Record<string, unknown>> = {",
    ...documents.map((path, i) => `${JSON.stringify(path)}: document${i},`),
    "};",
  ].join("\n"),
  { ...(await resolveConfig(output.pathname)), filepath: output.pathname },
);
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source) throw new Error("Run npm run content:build");
} else writeFileSync(output, source);
