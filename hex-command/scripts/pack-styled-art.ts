/** Pack complete source sprites; never resize, recolor or infer grid cells. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";
import { format } from "prettier";
import { TERRAIN, TYPES } from "../src/game/engine";

const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check")) throw new Error("Use --check or no arguments");
const check = args.includes("--check");
const root = fileURLToPath(new URL("../", import.meta.url));
const styles = ["normal", "low-poly"] as const;
const metadata: Record<string, unknown> = {};
const terrainMetadata: Record<string, unknown> = {};
const terrainColors = JSON.parse(readFileSync(root + "art/styled/terrain-colors.json", "utf8"));
const frameName = (name: string) =>
  name === "bonearcher" ? "bone_archer" : name === "grove" ? "sacred_grove" : name;
function output(path: string, data: string | Buffer) {
  if (check) {
    if (!readFileSync(root + path).equals(Buffer.from(data))) {
      throw new Error(`Stale styled artwork: ${path}; run npm run art:build`);
    }
  } else writeFileSync(root + path, data);
}

function pack(style: string, kind: "units" | "terrain", sprites: { key: string; file: string }[]) {
  const tiles = sprites.map((sprite) => ({
    ...sprite,
    image: PNG.sync.read(readFileSync(root + sprite.file)),
  }));
  const gutter = 4;
  let x = gutter,
    y = gutter,
    rowHeight = 0,
    width = 0;
  const frames: Record<string, number[]> = {};
  for (const { key, image } of tiles) {
    if (x + image.width + gutter > 2048) {
      x = gutter;
      y += rowHeight + gutter;
      rowHeight = 0;
    }
    frames[key] = [x, y, image.width, image.height];
    width = Math.max(width, x + image.width + gutter);
    rowHeight = Math.max(rowHeight, image.height);
    x += image.width + gutter;
  }
  const height = y + rowHeight + gutter;
  const atlas = new PNG({ width, height });
  const data = atlas.data;
  for (const { key, image } of tiles) {
    const [x, y] = frames[key]!;
    for (let row = 0; row < image.height; row++) {
      image.data.copy(
        data,
        ((y! + row) * width + x!) * 4,
        row * image.width * 4,
        (row + 1) * image.width * 4,
      );
    }
  }
  const png = PNG.sync.write(atlas, { colorType: 6, deflateLevel: 9 });
  const filename = `${kind}-${style}.png`;
  output(`public/assets/${filename}`, png);
  const result = {
    source: {
      filename,
      width,
      height,
      revision: createHash("sha256").update(png).digest("hex").slice(0, 12),
    },
    frames,
  };
  console.log(`${check ? "Checked" : "Packed"} ${style} ${kind}: ${tiles.length} complete sprites`);
  return result;
}
for (const style of styles) {
  const sprites = Object.keys(TYPES)
    .sort()
    .flatMap((type) =>
      ["enemy", "player"].map((side) => ({
        key: `${side}_${frameName(type)}`,
        file: `art/styled/${style}/units/${type}/${side}.png`,
      })),
    );
  sprites.push({
    key: "portrait_worker",
    file: `art/styled/${style}/portraits/worker/portrait.png`,
  });
  metadata[style] = pack(style, "units", sprites);
  terrainMetadata[style] = pack(
    style,
    "terrain",
    Object.keys(TERRAIN)
      .sort()
      .map((type) => ({
        key: `terrain_${frameName(type)}`,
        file: `art/styled/${style}/terrain/${type}/tile.png`,
      })),
  );
}
output(
  "src/presentation/styled-art.ts",
  await format(
    'import type { TerrainType } from "../game/types";\n' +
      "// Generated by scripts/pack-styled-art.ts; edit art/styled source sprites.\n" +
      "export const styledSheets = " +
      JSON.stringify(metadata) +
      " as const;\n" +
      "export const styledTerrainSheets = " +
      JSON.stringify(terrainMetadata) +
      " as const;\n" +
      'export const styledTerrainColors: Record<"normal" | "low-poly", Partial<Record<TerrainType, string>>> = ' +
      JSON.stringify(terrainColors) +
      ";\n",
    { parser: "typescript" },
  ),
);
